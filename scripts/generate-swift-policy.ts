// Writes the Swift copy of the region table (swift/Sources/HranessAnalytics/PolicyTable.swift) from src/policy.ts,
// so the Mac and iPhone apps read the same table as the browser, the edge and the CLI. `--check` fails when the
// committed file is stale.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import {
  BR_COUNTRIES,
  BR_ZONE,
  EU_COUNTRIES,
  EU_ZONE,
  PLACELESS_ZONE,
  REGION_TABLE,
  UK_CH_COUNTRIES,
  UK_CH_ZONE,
  US_COUNTRIES,
  US_ZONE,
} from "../src/policy.ts";

const target = resolve(import.meta.dir, "../swift/Sources/HranessAnalytics/PolicyTable.swift");
const set = (values: readonly string[]) => `[${values.map((value) => `"${value}"`).join(", ")}]`;
const pattern = (regex: RegExp) => `#"${regex.source.replaceAll("\\/", "/")}"#`;
const rule = (group: keyof typeof REGION_TABLE) => {
  const value = REGION_TABLE[group];
  return `        .${group === "uk_ch" ? "ukCh" : group}: Rule(analytics: .${value.analytics}, autocapture: ${String(value.autocapture)}, replay: ${String(value.replay)}, ads: ${String(value.ads)}, ask: .${value.ask === "none" ? "nothing" : value.ask}),`;
};

const source = `// Generated by scripts/generate-swift-policy.ts from src/policy.ts. Do not edit by hand.

enum PolicyTable {
    static let euCountries: Set<String> = ${set(EU_COUNTRIES)}
    static let ukChCountries: Set<String> = ${set(UK_CH_COUNTRIES)}
    static let brCountries: Set<String> = ${set(BR_COUNTRIES)}
    static let usCountries: Set<String> = ${set(US_COUNTRIES)}

    static let placelessZone = ${pattern(PLACELESS_ZONE)}
    static let ukChZone = ${pattern(UK_CH_ZONE)}
    static let euZone = ${pattern(EU_ZONE)}
    static let brZone = ${pattern(BR_ZONE)}
    static let usZone = ${pattern(US_ZONE)}

    static let rules: [RegionGroup: Rule] = [
${(["eu", "uk_ch", "br", "us", "row"] as const).map(rule).join("\n")}
    ]
}
`;

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== source) {
    console.error("swift/Sources/HranessAnalytics/PolicyTable.swift is stale; run bun run swift:policy");
    process.exit(1);
  }
} else {
  await writeFile(target, source);
}
