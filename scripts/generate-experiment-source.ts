// Writes src/experiment-source.ts: the minified source of `pick` from src/experiment-pick.ts, as a string constant
// that `experimentScript` inlines. A string survives any consumer's bundler, where `pick.toString()` would not (a
// `keepNames` build or an old target can add helpers from outside the function). `--check` fails when it is stale.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { pick } from "../src/experiment-pick.ts";

const target = resolve(import.meta.dir, "../src/experiment-source.ts");
const marker = "globalThis.__pick=";
const minified = new Bun.Transpiler({ loader: "js", minifyWhitespace: true })
  .transformSync(`${marker}${pick.toString()};`)
  .trim();
if (!minified.startsWith(marker) || !minified.endsWith(";")) throw new Error(`unexpected minified pick: ${minified.slice(0, 80)}`);
const body = minified.slice(marker.length, -1);
const source = `// Generated by scripts/generate-experiment-source.ts from src/experiment-pick.ts. Do not edit by hand.

/** The source of \`pick\`, minified, for the inline script \`experimentScript\` returns. */
export const PICK_SOURCE = ${JSON.stringify(body)};
`;

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== source) {
    console.error("src/experiment-source.ts is stale; run `bun run experiment:source`");
    process.exit(1);
  }
} else {
  await writeFile(target, source);
}
